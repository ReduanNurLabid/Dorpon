@app.get("/api/feed/buzz")
@app.get("/api/feed/top-stories")
def get_daily_buzz_feed(
    interests: Optional[str] = Query(None, description="Comma-separated interest tags e.g. economy_business,tech_innovation"),
    limit: int = 5
):
    """
    Returns automated Top Stories feed (2-section narrative summaries + clustered issue).
    Current Affairs articles are kept strictly separate.
    """
    top_data = load_top_stories_feed()
    if top_data and "stories" in top_data:
        stories = top_data["stories"]
        user_interest_list = [i.strip() for i in interests.split(",")] if interests else []
        if user_interest_list:
            filtered = [
                s for s in stories
                if any(c in user_interest_list for c in s.get("interestCategories", []))
            ]
            if filtered:
                stories = filtered
        return {
            "edition_date": top_data.get("edition_date", "2026-10-20"),
            "user_interests": user_interest_list,
            "count": len(stories[:limit]),
            "stories": stories[:limit]
        }
        
    capsule = load_latest_capsule()
    if not capsule:
        raise HTTPException(status_code=404, detail="No stories available.")
        
    regular_stories = [s for s in capsule.stories if not s.story_id.startswith("story-editorial") and not s.story_id.startswith("story-houthi")]
    if not regular_stories:
        regular_stories = capsule.stories

    user_interest_list = [i.strip() for i in interests.split(",")] if interests else []
    filtered = filter_feed_for_user_interests(regular_stories, user_interest_list, limit=limit)
    
    buzz_feed = []
    for s in filtered:
        item = s.model_dump()
        item.pop("bcs_pro", None)
        buzz_feed.append(item)
        
    return {
        "edition_date": capsule.edition_date,
        "user_interests": user_interest_list,
        "count": len(buzz_feed),
        "stories": buzz_feed
    }

@app.get("/api/feed/bcs-pro")
@app.get("/api/feed/current-affairs")
def get_bcs_pro_feed():
    """
    Returns the Current Affairs editorial question-led articles.
    """
    affairs_data = load_current_affairs_feed()
    if affairs_data and "stories" in affairs_data:
        return affairs_data

    capsule = load_latest_capsule()
    if not capsule:
        raise HTTPException(status_code=404, detail="No capsule generated yet.")
        
    bcs_stories = [s for s in capsule.stories if s.story_id in capsule.bcs_pro_preset_story_ids]
    if not bcs_stories:
        bcs_stories = capsule.stories
    
    return {
        "edition_date": capsule.edition_date,
        "preset_type": "Current Affairs Editorial Canon",
        "count": len(bcs_stories),
        "stories": [s.model_dump() for s in bcs_stories]
    }

