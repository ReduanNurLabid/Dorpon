def load_current_affairs_feed() -> Optional[dict]:
    if os.path.exists(CURRENT_AFFAIRS_FILE):
        with open(CURRENT_AFFAIRS_FILE, "r", encoding="utf-8") as f:
            return json.load(f)
    if os.path.exists(OUTPUT_FILE):
        with open(OUTPUT_FILE, "r", encoding="utf-8") as f:
            return json.load(f)
    return None

def load_latest_capsule() -> Optional[DailyCapsule]:
    if not os.path.exists(OUTPUT_FILE):
        return None
    with open(OUTPUT_FILE, "r", encoding="utf-8") as f:
        data = json.load(f)
        return DailyCapsule(**data)

def save_latest_capsule(capsule: DailyCapsule):
    with open(OUTPUT_FILE, "w", encoding="utf-8") as f:
        json.dump(capsule.model_dump(), f, ensure_ascii=False, indent=2)

